param(
    [string]$RawCsv = (Join-Path $PSScriptRoot '..\docs\benchmarks\interview_20261103\release_raw.csv'),
    [string]$SamplesCsv = '',
    [string]$Output = (Join-Path $PSScriptRoot '..\docs\benchmarks\interview_20261103\SUMMARY.md'),
    [ValidateSet('release', 'debug', 'unverified')]
    [string]$Mode = 'unverified'
)

$ErrorActionPreference = 'Stop'
$culture = [System.Globalization.CultureInfo]::InvariantCulture
$rows = @(Import-Csv -LiteralPath $RawCsv)
if ($rows.Count -eq 0) {
    throw 'No measurements in interview benchmark CSV'
}
$sourceShas = @($rows | Select-Object -ExpandProperty sha -Unique)
if ($sourceShas.Count -ne 1 -or [string]::IsNullOrWhiteSpace($sourceShas[0])) {
    throw 'All benchmark measurements must use one non-empty exact source SHA'
}

# New-format runs include executable profile/worktree state. Historical CSVs
# intentionally keep their original columns; their source log is the proof.
$columnNames = @($rows[0].PSObject.Properties.Name)
if ($columnNames -contains 'build_profile') {
    $profiles = @($rows | Select-Object -ExpandProperty build_profile -Unique)
    if ($profiles.Count -ne 1 -or ($Mode -ne 'unverified' -and $profiles[0] -ne $Mode)) {
        throw 'Requested build profile does not agree with recorded benchmark profile'
    }
    $dirty = @($rows | Select-Object -ExpandProperty git_dirty -Unique)
    if ($Mode -eq 'release' -and ($dirty.Count -ne 1 -or $dirty[0] -ne 'false')) {
        throw 'Release measurements require a clean, source-pinned worktree'
    }
    foreach ($r in $rows) {
        if ([int]$r.produce_sample_count -ne [int]$r.produced_records) {
            throw 'Producer samples do not match the produced record count'
        }
    }
}

if ($SamplesCsv) {
    $samples = @(Import-Csv -LiteralPath $SamplesCsv)
    if ($samples.Count -eq 0) { throw 'Raw latency samples are empty' }
    $expectedSamples = 0
    foreach ($r in $rows) {
        foreach ($metric in @('produce', 'fetch')) {
            $matching = @($samples | Where-Object {
                $_.sha -eq $r.sha -and $_.profile -eq $r.profile -and
                $_.acks -eq $r.acks -and $_.buffered -eq $r.buffered -and
                $_.repeat -eq $r.repeat -and $_.metric -eq $metric
            })
            $expectedCount = if ($metric -eq 'produce') { [int]$r.produced_records } else { [int]$r.fetched_records }
            $expectedSamples += $expectedCount
            if ($matching.Count -ne $expectedCount) {
                throw "Missing or duplicate $metric latency samples for $($r.profile)/$($r.acks)/$($r.repeat)"
            }
            [double[]]$sorted = @($matching | ForEach-Object {
                [double]::Parse($_.elapsed_ns, $culture)
            } | Sort-Object)
            foreach ($p in @(50, 95, 99)) {
                $rank = [math]::Max(1, [int][math]::Ceiling($sorted.Length * $p / 100.0))
                $actualMs = $sorted[$rank - 1] / 1000000.0
                $field = $metric + '_p' + $p + '_ms'
                $claimed = [double]::Parse($r.$field, $culture)
                if ([math]::Abs($actualMs - $claimed) -gt 0.0011) {
                    throw "Raw latency samples contradict $field for $($r.profile)/$($r.acks)/$($r.repeat)"
                }
            }
        }
    }
    if ($samples.Count -ne $expectedSamples) {
        throw 'Raw sample CSV contains rows not accounted for by the benchmark results'
    }
}

function MedianOf([object[]]$group, [string]$field) {
    [double[]]$numbers = @($group | ForEach-Object {
        [double]::Parse($_.$field, $culture)
    } | Sort-Object)
    $middle = [int][math]::Floor($numbers.Length / 2)
    if ($numbers.Length % 2 -eq 1) { return $numbers[$middle] }
    return ($numbers[$middle - 1] + $numbers[$middle]) / 2.0
}

$out = New-Object System.Collections.Generic.List[string]
$out.Add('# AstraLog — measured interview benchmark results')
$out.Add('')
$out.Add('Generated by `scripts/summarize-interview-benchmark.ps1` from `' + [System.IO.Path]::GetFileName($RawCsv) + '`; not hand-entered targets.')
$out.Add('')
$out.Add('Source benchmark Git SHA: `' + $sourceShas[0] + '`.')
if ($columnNames -contains 'build_profile') {
    $out.Add('Recorded executable profile: **' + $profiles[0] + '**; worktree dirty at measurement: **' + $dirty[0] + '** (caller requested **' + $Mode + '**).')
} else {
    $out.Add('Caller-supplied build profile: **' + $Mode + '** (historical CSV does not encode profile; cross-check the execution log).')
}
if ($SamplesCsv) {
    $out.Add('Verified raw Produce/Fetch request samples: **' + $samples.Count + '**; nearest-rank p50/p95/p99 independently rechecked against the raw sample CSV.')
}
if ($Mode -eq 'debug') {
    $out.Add('**DEBUG SMOKE ONLY: these numbers are not publishable optimized performance.**')
}
$out.Add('')
$out.Add('Metrics are **medians of per-repeat values**, not pooled percentiles or best-case runs.')
$out.Add('')
$out.Add('| Replicas | Acknowledgment | Buffered | Repeats | Total writes | Records/s | MiB/s | Produce p50 ms | Produce p95 ms | Produce p99 ms | Fetch p50 ms | Fetch p95 ms | Fetch p99 ms | Errors |')
$out.Add('|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|')

foreach ($group in ($rows | Group-Object profile, acks, buffered | Sort-Object Name)) {
    $members = @($group.Group)
    $first = $members[0]
    $bad = @($members | Where-Object {
        ([int]$_.producer_errors -ne 0) -or
        ([int]$_.produced_records -ne [int]$_.fetched_records)
    })
    if ($bad.Count -ne 0) {
        throw "Benchmark profile $($group.Name) has producer errors or incomplete committed fetch"
    }
    $totalWrites = [int](($members | Measure-Object -Property produced_records -Sum).Sum)
    $errors = [int](($members | Measure-Object -Property producer_errors -Sum).Sum)
    $values = @(
        $first.profile.ToUpperInvariant(), $first.acks, $first.buffered,
        $members.Count, $totalWrites,
        (MedianOf $members 'records_per_sec').ToString('F2', $culture),
        (MedianOf $members 'mib_per_sec').ToString('F3', $culture),
        (MedianOf $members 'produce_p50_ms').ToString('F2', $culture),
        (MedianOf $members 'produce_p95_ms').ToString('F2', $culture),
        (MedianOf $members 'produce_p99_ms').ToString('F2', $culture),
        (MedianOf $members 'fetch_p50_ms').ToString('F2', $culture),
        (MedianOf $members 'fetch_p95_ms').ToString('F2', $culture),
        (MedianOf $members 'fetch_p99_ms').ToString('F2', $culture),
        $errors
    )
    $out.Add('| ' + ($values -join ' | ') + ' |')
}

$out.Add('')
$smallSamples = @($rows | Where-Object { [int]$_.produced_records -lt 100 })
if ($smallSamples.Count -gt 0) {
    $out.Add('**Tail-latency caution:** ' + $smallSamples.Count + ' of ' + $rows.Count + ' measurement repeats contain fewer than 100 Produce samples. For nearest-rank p99, those values equal the slowest observed request in that repeat and do **not** establish a reliable production p99.')
    $out.Add('')
}
$windows = @($rows | Select-Object -ExpandProperty configured_ms -Unique)
$windowLabel = if ($windows.Count -eq 1) { $windows[0] + ' ms' } else { 'mixed per-row durations' }
$out.Add('**Measurement definition:** one 1,024-byte value per record; four concurrent producers; eight excluded warm-up records per topic; ' + $windowLabel + ' target produce window per repeat; each Fetch request asks for one committed record. Throughput uses the actual completed writes and observed elapsed time. MiB/s counts logical value bytes, not headers, protocol or replication traffic. Latency includes end-to-end client await time. Fetch measurements occur **after** production, not during simultaneous production.')
$out.Add('')
$out.Add('**Captured run environment (2026-11-03 baseline only):** Windows 11 Home Single Language (build 26200), Intel Core i7-13620H (10 cores/16 logical processors), 16.85 GB physical RAM, local loopback TCP, NTFS temporary data on C:. Three broker runtimes and three Raft metadata controllers share one test process for RF3. Rust 1.98.1. For a new run, use the launcher environment.txt rather than treating this baseline machine as the new host.')
$out.Add('')
$out.Add('**Limitations:** short repeats, one laptop in the retained baseline, no isolated hardware or network, and no reported SLA. RF1 is the standalone broker with no P8 buffered API; RF3 uses committed P8 feature level 4 for buffered writes. RF1 leader/quorum acknowledgments are not equivalent to comparing leader/quorum behavior in a multi-node cluster. No background consumers, WAN latency, compression comparison or multi-process deployment was measured. The broader P9-G release gate remains unqualified; these tests are interview-demo evidence only.')

$directory = Split-Path -Parent $Output
if (-not (Test-Path -LiteralPath $directory)) {
    New-Item -ItemType Directory -Path $directory -Force | Out-Null
}
# Use stable LF even when generating on Windows: Git whitespace checks and
# reproducible report hashes must not depend on the host line-ending policy.
$lf = [string][char]10
[System.IO.File]::WriteAllText($Output, ($out -join $lf) + $lf, (New-Object System.Text.UTF8Encoding($false)))
Write-Output ('Generated {0} from {1} rows at source {2}' -f $Output, $rows.Count, $sourceShas[0])
$out | ForEach-Object { Write-Output $_ }
